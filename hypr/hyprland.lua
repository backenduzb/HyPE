hl.config({ autogenerated = false })

require("hypr.theme.theme")
local themeName = os.getenv("HYCON_THEME")
if themeName == nil then
    themeName = "macos"
end
if themeName ~= "" then
    pcall(require, "themes." .. themeName .. ".hypr")
end
require("hypr.modules.animations")
require("hypr.modules.keybinds")
require("hypr.modules.autostart")

if os.getenv("HYCON_NESTED") == "1" then
    hl.monitor({
        output = "",
        mode = "1920x1080",
        position = "auto",
        scale = 1,
    })
end

if os.getenv("HYCON_DEBUG") == "1" then
    hl.config({
        debug = {
            enable_stdout_logs = true,
        },
    })
end

hl.layer_rule({
    match = { namespace = "waybar" },
    blur = true,
    xray = false,
})
hl.layer_rule({
    match = { namespace = "rofi" },
    blur = false,
    xray = false,
    animation = "popin 96%",
})
